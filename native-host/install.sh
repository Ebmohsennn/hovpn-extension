#!/usr/bin/env bash
# Installs the native messaging host manifest so Chrome will let the
# extension launch xray-manager.js. macOS-only paths (Darwin); adjust
# TARGET_DIR for Linux/Windows if needed.
set -euo pipefail

EXT_ID="${1:?Usage: ./install.sh <chrome-extension-id>}"
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Chrome launches native messaging hosts with a MINIMAL PATH
# (/usr/bin:/bin:/usr/sbin:/sbin) that excludes Homebrew (/opt/homebrew/bin),
# nvm, and most places Node actually gets installed. So a wrapper that relies
# on `env node` finding Node on PATH will fail with "Native host has exited."
# We resolve Node's absolute path NOW, at install time, and bake it into the
# wrapper so the runtime launch never depends on PATH.
NODE_BIN="$(command -v node || true)"
if [ -z "$NODE_BIN" ]; then
  echo "ERROR: could not find a 'node' binary on your PATH." >&2
  echo "Install Node.js (e.g. 'brew install node') and re-run this script." >&2
  exit 1
fi
# Resolve symlinks (e.g. Homebrew/nvm shims) to a stable absolute path.
NODE_BIN="$(cd "$(dirname "$NODE_BIN")" && pwd)/$(basename "$NODE_BIN")"
echo "Using Node at: $NODE_BIN"

chmod +x "$DIR/xray-manager.js"

WRAPPER="$DIR/xray-manager-host"
cat > "$WRAPPER" <<EOF
#!/bin/bash
# Auto-generated by install.sh. Uses an absolute Node path because Chrome
# launches native messaging hosts with a minimal PATH (no Homebrew/nvm).
exec "$NODE_BIN" "$DIR/xray-manager.js"
EOF
chmod +x "$WRAPPER"

TARGET_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
mkdir -p "$TARGET_DIR"

sed -e "s#REPLACED_BY_INSTALL_SCRIPT_ABS_PATH#$WRAPPER#" \
    -e "s#REPLACED_EXTENSION_ID#$EXT_ID#" \
    "$DIR/com.v2raychrome.xraymanager.json" > "$TARGET_DIR/com.v2raychrome.xraymanager.json"

echo "Installed native messaging host for extension $EXT_ID"
echo "Manifest: $TARGET_DIR/com.v2raychrome.xraymanager.json"
echo "Now reload the extension at chrome://extensions and try Connect."
